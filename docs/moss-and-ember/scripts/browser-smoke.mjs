import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';

const localChrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync(localChrome) ? localChrome : undefined);
const browser = await chromium.launch({ headless:true, executablePath });
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
page.on('pageerror',error=>errors.push(error.message));
await mkdir('.test-artifacts',{recursive:true});
try {
  await page.goto(process.env.GAME_URL || 'http://localhost:5173');
  await page.waitForFunction(()=>window.__MOSS_EMBER__);
  await page.screenshot({path:'.test-artifacts/title.png'});
  await page.getByRole('button',{name:'Begin your journey'}).click();
  await page.locator('#dialog-next').click();
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.state),'playing');
  const initialY=await page.evaluate(()=>window.__MOSS_EMBER__.game.player.y);
  await page.keyboard.down('w');
  await page.waitForFunction(y=>window.__MOSS_EMBER__.game.player.y<y-40,initialY,{timeout:10000});
  await page.keyboard.up('w');
  assert.ok(await page.evaluate(y=>window.__MOSS_EMBER__.game.player.y<y-30,initialY),'Keyboard moves player');
  await page.keyboard.press('j');
  await page.keyboard.press('Space');
  await page.waitForTimeout(400);
  await page.screenshot({path:'.test-artifacts/forest.png'});
  await page.keyboard.press('m');await page.locator('#map-screen').waitFor({state:'visible'});
  await page.screenshot({path:'.test-artifacts/map.png'});
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');await page.locator('#pause-screen').waitFor({state:'visible'});
  const pausedY=await page.evaluate(()=>window.__MOSS_EMBER__.game.player.y);
  await page.keyboard.down('w');await page.waitForTimeout(100);await page.keyboard.up('w');
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.player.y),pausedY,'Pause stops movement');
  await page.locator('#resume-button').click();
  await page.keyboard.press('m');
  await page.waitForFunction(()=>window.__MOSS_EMBER__.game.mapOpen);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await page.locator('#pause-screen').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.mapOpen),false,'Losing focus from the map pauses safely');
  await page.locator('#resume-button').click();
  await page.evaluate(()=>{const g=window.__MOSS_EMBER__.game;g.player.hp=2;});
  await page.keyboard.press('q');
  await page.waitForFunction(()=>window.__MOSS_EMBER__.game.player.hp===6);
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.player.hp),6,'Tonic heals');
  await page.evaluate(()=>{const g=window.__MOSS_EMBER__.game;g.save();});
  await page.reload();await page.waitForFunction(()=>window.__MOSS_EMBER__);
  await page.locator('#continue-button').click();
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.player.potions),2,'Continue restores inventory');
  await page.evaluate(()=>{
    const g=window.__MOSS_EMBER__.game;
    Object.assign(g.progress,{westShrine:true,eastShrine:true,templeOpened:true,templeKey:true,westSwitch:true,eastSwitch:true,bossGate:true});
    g.player.magic=true;g.changeWorld('temple',false);
    g.player.y=390;g.player.x=575;g.camera.x=575;g.camera.y=320;g.player.hurtTimer=30;
  });
  await page.waitForTimeout(1500);
  await page.locator('#boss-panel').waitFor({state:'visible'});
  assert.equal(await page.locator('#boss-health-meter').getAttribute('aria-valuenow'),'42','Boss health is visible');
  await page.screenshot({path:'.test-artifacts/temple.png'});
  await page.keyboard.press('k');
  await page.waitForFunction(()=>window.__MOSS_EMBER__.game.player.mana<6);
  assert.ok(await page.evaluate(()=>window.__MOSS_EMBER__.game.player.mana<6),'Magic consumes energy');
  await page.evaluate(()=>{
    const g=window.__MOSS_EMBER__.game,b=g.enemies.find(e=>e.type==='boss');
    g.hitEnemy(b,b.hp,0);g.player.x=576;g.player.y=204;g.interact();
  });
  await page.locator('#victory-screen').waitFor({state:'visible'});
  await page.screenshot({path:'.test-artifacts/victory.png'});
  assert.equal(await page.evaluate(()=>window.__MOSS_EMBER__.game.progress.won),true);

  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(process.env.GAME_URL || 'http://localhost:5173');
  await mobile.waitForFunction(()=>window.__MOSS_EMBER__);
  await mobile.screenshot({path:'.test-artifacts/mobile-title.png'});
  await mobile.locator('#start-button').tap();
  await mobile.locator('#dialog-next').tap();
  assert.equal(await mobile.locator('#touch-controls').isVisible(),true,'Touch controls visible');
  const mobileY=await mobile.evaluate(()=>window.__MOSS_EMBER__.game.player.y);
  const touchUp=await mobile.locator('[data-touch="up"]').boundingBox();
  const cdp=await mobile.context().newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:touchUp.x+touchUp.width/2,y:touchUp.y+touchUp.height/2}]});
  await mobile.waitForFunction(y=>window.__MOSS_EMBER__.game.player.y<y-20,mobileY,{timeout:10000});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.ok(await mobile.evaluate(y=>window.__MOSS_EMBER__.game.player.y<y-15,mobileY),'Real touch input moves player');
  await mobile.screenshot({path:'.test-artifacts/mobile-game.png'});
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No mobile horizontal overflow');
  assert.deepEqual(errors,[],'No browser runtime errors');
  console.log('Browser smoke passed: title, keyboard movement, combat input, map, pause, healing, save/continue, temple, magic, victory, and mobile layout. Screenshots: .test-artifacts/');
} finally { await browser.close(); }
